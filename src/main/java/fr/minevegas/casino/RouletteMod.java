   public static void onChunkLoad(ServerLevel level, LevelChunk chunk) {
      chunk.findBlocks((state) -> state.is(FORTUNE_WHEEL) && (Integer)state.getValue(FortuneWheelBlock.PART) == 4, (pos, state) -> level.scheduleTick(pos, FORTUNE_WHEEL, 1));
      chunk.findBlocks((state) -> state.is(DUCK_DERBY) && (Integer)state.getValue(DuckDerbyBlock.PART) == 10, (pos, state) -> level.scheduleTick(pos, DUCK_DERBY, 1));
      chunk.findBlocks((state) -> state.is(SLOT_MACHINE) && state.getValue(SlotMachineBlock.HALF) != SlotMachinePart.TOP, (pos, state) -> level.scheduleTick(pos, SLOT_MACHINE, 1));
      chunk.findBlocks((state) -> state.is(PLINKO) && (Integer)state.getValue(PlinkoBlock.PART) == 4, (pos, state) -> level.scheduleTick(pos, PLINKO, 1));
   }

